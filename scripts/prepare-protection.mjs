#!/usr/bin/env node
// Rebuild Chinese and Japanese protection metadata; never touches artwork or personal records.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check')) throw new Error('用法：node scripts/prepare-protection.mjs [--check]');
const data = JSON.parse(fs.readFileSync(path.join(root, 'assets/research/national-protection.json'), 'utf8'));
const japan = JSON.parse(fs.readFileSync(path.join(root, 'assets/research/japanese-protection.json'), 'utf8'));
const { SITES, DYN } = vm.runInNewContext(fs.readFileSync(path.join(root, 'sites.js'), 'utf8') + '\n({ SITES, DYN })');
const ids = new Set(SITES.map(site => site.id));
const fail = message => { throw new Error(`国保资料：${message}`); };
if (data.version !== 1 || data.level !== '全国重点文物保护单位' || !/^\d{4}-\d{2}-\d{2}$/.test(data.checkedAt)) fail('无效版本、制度或核对日期');
const officialURL = value => {
  const url = new URL(value);
  return url.protocol === 'https:' && (url.hostname.endsWith('.gov.cn') || url.hostname === 'zjjcmspublic.oss-cn-hangzhou-zwynet-d01-a.internet.cloud.zj.gov.cn');
};
for (const [key, source] of Object.entries(data.sources)) {
  if (!Number.isInteger(source.batch) || source.batch < 1 || !source.title || !officialURL(source.url)
      || !/^\d{4}-\d{2}-\d{2}$/.test(source.announcedOn) || !/^[a-f0-9]{64}$/.test(source.retrievedSha256)) fail(`无效官方来源 ${key}`);
}
for (const [id, entries] of Object.entries(data.entries)) {
  if (!ids.has(id) || !Array.isArray(entries) || !entries.length || data.untagged[id]) fail(`无效或冲突的古迹 ${id}`);
  const seen = new Set();
  for (const entry of entries) {
    const source = data.sources[entry.source], key = `${entry.batch}|${entry.unitName}`;
    if (!source || entry.batch !== source.batch || !entry.unitName || !entry.scope || !entry.locator
        || !['unit', 'part', 'merged'].includes(entry.relation) || seen.has(key)) fail(`${id} 的登记字段无效或重复`);
    seen.add(key);
    if (entry.relation === 'merged' && (!entry.parent?.unitName || !Number.isInteger(entry.parent.batch) || entry.parent.batch >= entry.batch || !entry.note)) fail(`${id} 缺少真实合并关系`);
    if (entry.scopeSources?.some(source => !source.title || !officialURL(source.url))) fail(`${id} 的范围来源无效`);
  }
}
for (const [id, review] of Object.entries(data.untagged)) {
  if (!ids.has(id) || !['unconfirmed', 'related_site', 'not_applicable'].includes(review.status) || !review.reason) fail(`无效待核对说明 ${id}`);
}
const japaneseIDs = new Set(SITES.filter(site => DYN[site.dyn].country === 'JP').map(site => site.id));
if (japan.version !== 1 || !/^\d{4}-\d{2}-\d{2}$/.test(japan.checkedAt)) fail('无效日本资料版本或核对日期');
for (const [key, source] of Object.entries(japan.sources)) {
  const url = new URL(source.url);
  if (!key.startsWith('jp_') || !source.title || !source.publisher || url.protocol !== 'https:'
      || !url.hostname.endsWith('.bunka.go.jp') || !/^[a-f0-9]{64}$/.test(source.retrievedSha256)
      || !/^\d{4}-\d{2}-\d{2}$/.test(source.retrievedOn)) fail(`无效日本官方来源 ${key}`);
}
for (const [id, entries] of Object.entries(japan.entries)) {
  if (!japaneseIDs.has(id) || !Array.isArray(entries) || !entries.length || japan.untagged[id]) fail(`无效日本古迹 ${id}`);
  const seen = new Set();
  for (const entry of entries) {
    const key = `${entry.source}|${entry.unitName}`;
    if (entry.system !== 'JP' || entry.batch !== null || !japan.sources[entry.source]
        || !['national_treasure', 'important_cultural_property'].includes(entry.designation)
        || !['unit', 'part'].includes(entry.relation) || !entry.unitName || !entry.scope || !entry.locator
        || !/^\d{4}-\d{2}-\d{2}$/.test(entry.designatedOn) || seen.has(key)) fail(`${id} 的日本指定资料无效或重复`);
    seen.add(key);
  }
}
for (const [id, review] of Object.entries(japan.untagged)) {
  if (!japaneseIDs.has(id) || !['unconfirmed', 'outside_scope'].includes(review.status) || !review.reason
      || !review.evidence?.length || review.evidence.some(url => !/^https:\/\//.test(url))) fail(`无效日本未贴标签说明 ${id}`);
}
// New catalogue IDs may be unverified: lack of a title does not block prototype intake.
const output = `/* Generated by scripts/prepare-protection.mjs; edit assets/research/national-protection.json or japanese-protection.json. */\n(function (root, factory) {\n  if (typeof module === 'object' && module.exports) module.exports = factory();\n  else root.FangguProtectionData = factory();\n})(typeof globalThis === 'object' ? globalThis : this, () => (${JSON.stringify({ ...data, japan }, null, 2)}));\n`;
const target = path.join(root, 'protection-data.js');
if (args.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fail('protection-data.js 过期，请重建');
} else fs.writeFileSync(target, output);
const pending = SITES.filter(site => !data.entries[site.id] && !data.untagged[site.id]);
console.log(`${args.includes('--check') ? '核对' : '生成'}国保资料：${Object.keys(data.entries).length} 处有标签，${Object.keys(data.untagged).length} 处未贴，${pending.length} 处新增待核对`);
console.log(`日本保护资料：${Object.keys(japan.entries).length} 处有标签，${Object.keys(japan.untagged).length} 处未贴`);
